/**
 * Prepares the pages for a fast first load, from the files you edit:
 *
 * 1. css/site.css: every stylesheet css/main.css lists, in its order, in one file. One request
 *    instead of one per file is what lets phones draw the page sooner. The sources stay one file per
 *    component; edit those and css/main.css, never site.css.
 * 2. In every HTML page that runs js/main.js, the block between the preload markers: the
 *    stylesheet, the page's content files and every JavaScript module main.js imports, directly
 *    or through other modules, and a copy of js/head.js. The browser would otherwise find the
 *    modules one level at a time (main.js → sections → components → …, six levels deep) and
 *    fetch the content only after all of them had run; announced up front, everything
 *    downloads in parallel.
 *
 * Run after changing any stylesheet or js/head.js, or adding, removing or renaming a module or
 * content file: `npm run preload` (the tests fail when the output is out of date).
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, posix, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { PAGES, SITE_CONTENT } from '../public/js/config.js'

export const PUBLIC_DIR = fileURLToPath(new URL('../public/', import.meta.url))
export const STYLESHEET = 'css/site.css'
const ENTRY = join(PUBLIC_DIR, 'js/main.js')
const START = '<!-- preload:start (generated by `npm run preload`) -->'
const END = '<!-- preload:end -->'
/** The blog's list of articles (written when publishing; the dev server makes it on request). */
const POST_INDEX = 'content/posts/index.json'

/** Relative paths in `import … from './x.js'`, `export … from './x.js'` and `import './x.js'`. */
const IMPORT_PATTERN = /^\s*(?:import|export)\s(?:[^'"]*?\sfrom\s)?['"](\.{1,2}\/[^'"]+)['"]/gm

/** Every module the entry imports, directly or indirectly, as paths relative to /public. */
export function moduleGraph(entry = ENTRY) {
  const found = new Set()
  const visit = (file) => {
    for (const [, specifier] of readFileSync(file, 'utf8').matchAll(IMPORT_PATTERN)) {
      const target = resolve(dirname(file), specifier)
      if (found.has(target)) continue
      found.add(target)
      visit(target)
    }
  }
  visit(entry)
  return [...found].map((file) => relative(PUBLIC_DIR, file)).sort()
}

/** The stylesheets css/main.css imports, in its order, relative to css/ ("base/tokens.css"). */
export function stylesheets() {
  const main = readFileSync(join(PUBLIC_DIR, 'css/main.css'), 'utf8')
  return [...main.matchAll(/@import url\('([^']+)'\)/g)].map(([, file]) => file)
}

/**
 * All stylesheets in one: each file in turn, its `url()` paths rewritten from its own folder to
 * css/ (base/fonts.css's '../../fonts/x.woff2' becomes '../fonts/x.woff2').
 */
export function bundleStylesheets(files = stylesheets()) {
  const parts = files.map((file) => {
    const css = readFileSync(join(PUBLIC_DIR, 'css', file), 'utf8')
    const folder = posix.dirname(file)
    const rebased = css.replace(/url\('([^']+)'\)/g, (match, path) =>
      path.startsWith('data:') ? match : `url('${posix.normalize(posix.join(folder, path))}')`,
    )
    return `/* ---- ${file} ---- */\n\n${rebased.trim()}\n`
  })
  const header =
    '/* Generated from css/main.css by `npm run preload`: edit the files it lists, not this one. */'
  return [header, ...parts].join('\n')
}

/** The HTML pages that run the site (redirect pages do not). */
export const sitePages = () =>
  readdirSync(PUBLIC_DIR).filter(
    (file) =>
      file.endsWith('.html') && readFileSync(join(PUBLIC_DIR, file), 'utf8').includes('js/main.js'),
  )

/**
 * js/head.js, to be written into the page: one request fewer before the first paint (it would be
 * the last thing a phone waits for). Edit js/head.js; the pages get a copy.
 */
const headScript = () =>
  readFileSync(join(PUBLIC_DIR, 'js/head.js'), 'utf8')
    .trim()
    .split('\n')
    // Indented as Prettier indents a script in <head> (it leaves the code itself as it is).
    .map((line) => (line ? `      ${line}` : line))
    .join('\n')

/**
 * The block for a page's <head>: the stylesheet, the content and the modules to fetch, and the
 * head script (last, so the browser has seen everything to fetch before it runs).
 */
export function renderBlock(html, modules = moduleGraph(), script = headScript()) {
  const pageKey = html.match(/data-page="([\w-]+)"/)?.[1]
  const content = [
    ...SITE_CONTENT.map((name) => `content/${name}.json`),
    ...(PAGES.includes(pageKey) ? [`content/pages/${pageKey}.json`] : []),
    ...(pageKey === 'blog' ? [POST_INDEX] : []),
  ]
  const lines = [
    START,
    `<link rel="stylesheet" href="${STYLESHEET}" />`,
    ...content.map((file) => `<link rel="preload" href="${file}" as="fetch" crossorigin />`),
    ...modules.map((file) => `<link rel="modulepreload" href="${file}" />`),
    `<script>\n${script}\n    </script>`,
    END,
  ]
  return lines.join('\n    ')
}

/** The page with its preload block brought up to date. */
export function withPreloads(html, modules) {
  const block = renderBlock(html, modules)
  const start = html.indexOf(START)
  const end = html.indexOf(END)
  if (start === -1 || end === -1) throw new Error(`no ${START} … ${END} block`)
  return html.slice(0, start) + block + html.slice(end + END.length)
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(join(PUBLIC_DIR, STYLESHEET), bundleStylesheets())
  const modules = moduleGraph()
  for (const file of sitePages()) {
    const path = join(PUBLIC_DIR, file)
    writeFileSync(path, withPreloads(readFileSync(path, 'utf8'), modules))
  }
  console.log(
    `Written: ${STYLESHEET} (${stylesheets().length} stylesheets), preloads for ` +
      `${modules.length} modules in ${sitePages().length} pages`,
  )
}
